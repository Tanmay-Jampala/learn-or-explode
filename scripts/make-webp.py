"""Convert the notebook figures (PNG) into 1x and 2x WebP files and record their display sizes.

Run after the notebook has produced new figures:
    python scripts/make-webp.py "<path to project>/figures"
"""
import json
import sys
from pathlib import Path

from PIL import Image

SITE = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
out = SITE / "figures"
out.mkdir(exist_ok=True)
for old in out.glob("*"):
    old.unlink()

sizes = {}
for png in sorted(source.glob("fig*.png")):
    image = Image.open(png).convert("RGB")
    key = png.stem[:5]                                   # fig01 ... fig14
    for width, tag in ((800, "1x"), (1600, "2x")):
        w = min(width, image.width)
        h = round(image.height * w / image.width)
        image.resize((w, h), Image.LANCZOS).save(out / f"{key}-{tag}.webp", "WEBP", quality=82, method=6)
    sizes[key] = [800, round(image.height * 800 / image.width)]

(SITE / "src" / "data" / "figure-sizes.js").write_text(
    "// Generated by scripts/make-webp.py: display size (width, height) of each 1x figure.\n"
    f"export default {json.dumps(sizes)};\n", encoding="utf-8")
total = sum(f.stat().st_size for f in out.glob("*")) / 1e6
print(f"make-webp: {len(sizes)} figures, {total:.2f} MB")

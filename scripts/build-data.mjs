// Reads data/results.json (written by the notebook), checks it against the reference values in the
// brief (§2) and writes src/data/results.js. The build fails if any number disagrees.
import { readFileSync, writeFileSync } from "node:fs";

const R = JSON.parse(readFileSync("data/results.json", "utf8"));
const run = (eta) => R.gd_runs.find((r) => Math.abs(r.eta - eta) < 1e-9);
const RUNS = [[0.1, 621, "converged"], [0.5, 119, "converged"], [1.0, 59, "converged"], [1.1, 323, "converged"],
  [1.12, 1637, "converged"], [1.13, 1471, "exploded"], [1.15, 299, "exploded"]];

// [name, value from results.json, reference value, decimal places compared (omit for exact match)]
const checks = [
  ["rho", R.rho, 0.7777, 4], ["b1", R.b[0], 0.8407, 4], ["b2", R.b[1], 0.5910, 4],
  ["det A", R.hessian_test.rt_minus_s2, 0.3951, 4],
  ["w*1", R.w_star[0], 0.9645, 4], ["w*2", R.w_star[1], -0.1592, 4],
  ["Gauss-Seidel iterations", R.gauss_seidel.iterations, 24, 0], ["Jacobi iterations", R.jacobi_iterations, 56, 0],
  ["lambda max", R.eigenvalues[1], 1.7777, 4], ["lambda min", R.eigenvalues[0], 0.2223, 4],
  ["steep eigenvector x", R.eigenvectors[1][0] * Math.SQRT2, 1, 4], ["steep eigenvector y", R.eigenvectors[1][1] * Math.SQRT2, 1, 4],
  ["flat eigenvector x", R.eigenvectors[0][0] * Math.SQRT2, -1, 4], ["flat eigenvector y", R.eigenvectors[0][1] * Math.SQRT2, 1, 4],
  ["kappa", R.condition_number, 7.9988, 4],
  ["rupees per sqft", R.w_original_units.lakhs_per_sqft * 1e5, 10836, 0],
  ["lakh per BHK", R.w_original_units.lakhs_per_bhk, -15.2, 1], ["R squared", R.r_squared, 0.717, 3],
  ["Lagrange s", R.lagrange.s, 0.6, 1], ["mu", R.lagrange.mu, 0.2879, 4],
  ["w_c1", R.lagrange.w_c[0], 0.5913, 4], ["w_c2", R.lagrange.w_c[1], 0.1018, 4],
  ["time constant slow", R.time_constants[0], 4.4994, 4], ["time constant fast", R.time_constants[1], 0.5625, 4],
  ["critical momentum gamma", R.momentum_critical_gamma[0], 0.9429, 4],
  ["eta crit", R.eta_crit, 1.12502, 5], ["eta opt", R.eta_opt, 1.0, 2],
  ["factor at eta opt", run(1.0).factor, 0.7777, 4], ["zig-zag threshold 1/lambda max", 1 / R.eigenvalues[1], 0.5625, 4],
  ["factor 1.12", run(1.12).factor, 0.9911, 4], ["factor 1.13", run(1.13).factor, 1.0089, 4],
  ...RUNS.flatMap(([eta, steps, outcome]) => [[`steps at ${eta}`, run(eta).steps, steps, 0], [`outcome at ${eta}`, run(eta).outcome, outcome]]),
  ["w0", R.w0.join(","), "-1.5,-1"],
];

const bad = checks.filter(([, got, want, dp]) =>
  dp === undefined ? got !== want : Number(got.toFixed(dp)) !== Number(want.toFixed(dp)));
if (bad.length) {
  console.error("results.json disagrees with the reference values (brief §2):");
  bad.forEach(([name, got, want]) => console.error(`  ${name}: got ${got}, expected ${want}`));
  process.exit(1);
}
writeFileSync("src/data/results.js",
  "// Generated by scripts/build-data.mjs from data/results.json. Do not edit.\n" +
  `export default ${JSON.stringify(R)};\n`);
console.log(`build-data: all ${checks.length} reference values match`);
